# build-template.ps1 (Windows; macOS and Linux use build-template.sh)
# Builds templates\et-al.template.yaml, the template anyone can import in
# Switch Console, from templates\et-al.template.src.yaml and the instruction
# files in agents\ and room\. Run it after editing any of them:
#   .\scripts\build-template.ps1

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$src = Join-Path $root 'templates\et-al.template.src.yaml'
$out = Join-Path $root 'templates\et-al.template.yaml'

# The placeholders in agents\ and room\ become the template's own params
$map = [ordered]@{
    'STUDENT-USERNAME' = '{student}'
    'PI-USERNAME'      = '{$creator}'
    'YOUR-EMAIL'       = '{openalex_email}'
    'PYTHON-PATH'      = '{python}'
}
function ToParams([string]$t) { foreach ($k in $map.Keys) { $t = $t.Replace($k, $map[$k]) }; return $t }
function ReadText([string]$p) { ((Get-Content $p -Raw) -replace "`r`n", "`n").TrimEnd() }

$lines = New-Object System.Collections.Generic.List[string]
@(
    '# Et Al.: a research room with three agents on two models.'
    '# GENERATED by scripts/build-template from templates/et-al.template.src.yaml'
    '# and the files in agents/ and room/. Edit those, then rebuild.'
    '#'
    '# Import this file in Switch Console: Templates, then Import template.'
    '# Before running it, remove any existing coordinator, scout and'
    '# experimenter agents (names must be free), and sign in to Cursor and'
    '# Claude Code under Settings, Agent providers.'
) | ForEach-Object { $lines.Add($_) }

$header = $true
foreach ($line in ((ReadText $src) -split "`n")) {
    if ($header) {
        if ($line -match '^\s*#' -or $line.Trim() -eq '') { continue }
        $header = $false
    }
    if ($line -match '^(\s*)#include\s+(\S+)\s*$') {
        $indent = $Matches[1]
        $inc = $Matches[2]
        $p = Join-Path $root ($inc -replace '/', '\')
        if (-not (Test-Path $p)) { throw "Missing include: $inc" }
        $body = ReadText $p
        if ($body.Contains('{')) { throw "$inc contains {, which Switch reads as a template parameter" }
        foreach ($b in ($body -split "`n")) {
            if ($b.Trim() -eq '') { $lines.Add('') } else { $lines.Add($indent + (ToParams $b)) }
        }
    }
    else { $lines.Add($line) }
}
Set-Content -Path $out -Value (($lines -join "`n") + "`n") -Encoding utf8 -NoNewline
Write-Host 'Built templates\et-al.template.yaml'
