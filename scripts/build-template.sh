#!/usr/bin/env bash
# build-template.sh (macOS and Linux; Windows uses build-template.ps1)
# Builds templates/et-al.template.yaml, the template anyone can import in
# Switch Console, from templates/et-al.template.src.yaml and the instruction
# files in agents/ and room/. Run it after editing any of them:
#   bash scripts/build-template.sh

set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/templates/et-al.template.src.yaml"
OUT="$ROOT/templates/et-al.template.yaml"
export BUILD_ROOT="$ROOT"

awk '
function lit(s, from, to,   out, i) {
  out = ""
  while ((i = index(s, from)) > 0) { out = out substr(s, 1, i - 1) to; s = substr(s, i + length(from)) }
  return out s
}
# The placeholders in agents/ and room/ become the template'"'"'s own params
function param(s) {
  s = lit(s, "STUDENT-USERNAME", "{student}")
  s = lit(s, "PI-USERNAME",      "{$creator}")
  s = lit(s, "YOUR-EMAIL",       "{openalex_email}")
  s = lit(s, "PYTHON-PATH",      "{python}")
  return s
}
BEGIN {
  print "# Et Al.: a research room with three agents on two models."
  print "# GENERATED by scripts/build-template from templates/et-al.template.src.yaml"
  print "# and the files in agents/ and room/. Edit those, then rebuild."
  print "#"
  print "# Import this file in Switch Console: Templates, then Import template."
  print "# Before running it, remove any existing coordinator, scout and"
  print "# experimenter agents (names must be free), and sign in to Cursor and"
  print "# Claude Code under Settings, Agent providers."
  header = 1
}
{
  sub(/\r$/, "")
  if (header) { if ($0 ~ /^[ \t]*#/ || $0 ~ /^[ \t]*$/) next; header = 0 }
  if ($0 ~ /^[ \t]*#include[ \t]+[^ \t]+[ \t]*$/) {
    match($0, /^[ \t]*/); indent = substr($0, 1, RLENGTH)
    inc = $0; sub(/^[ \t]*#include[ \t]+/, "", inc); sub(/[ \t]*$/, "", inc)
    path = ENVIRON["BUILD_ROOT"] "/" inc
    n = 0
    while ((getline line < path) > 0) { sub(/\r$/, "", line); buf[++n] = line }
    close(path)
    if (n == 0) { print "Missing or empty include: " inc > "/dev/stderr"; exit 2 }
    while (n > 0 && buf[n] ~ /^[ \t]*$/) n--
    for (k = 1; k <= n; k++) {
      if (index(buf[k], "{") > 0) { print "Error: " inc " contains {, which Switch reads as a template parameter" > "/dev/stderr"; exit 3 }
      if (buf[k] ~ /^[ \t]*$/) print ""; else print indent param(buf[k])
    }
    next
  }
  print $0
}
' "$SRC" > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "Built templates/et-al.template.yaml"
